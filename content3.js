/* Получить всё для дашборда в одном вызове */
function getDashboardData(state){
  var snap = null;
  try {
    if (typeof buildUserSnapshot === 'function') snap = buildUserSnapshot(state);
  } catch(e){}
  var balance = null;
  try {
    if (typeof getSpheresBalance === 'function' && state && state.domainScores) {
      var today = new Date().toISOString().slice(0,10);
      var scores = state.domainScores[today] || {};
      balance = getSpheresBalance(scores);
    }
  } catch(e){}
  var phase = null;
  try {
    if (typeof getCurrentPhase === 'function') phase = getCurrentPhase();
  } catch(e){}
  var tip = null;
  try {
    if (balance && balance.weakest && typeof getRecommendationForWeakest === 'function') {
      var today2 = new Date().toISOString().slice(0,10);
      var scores2 = (state.domainScores||{})[today2]||{};
      tip = getRecommendationForWeakest(scores2);
    }
  } catch(e){}
  return {
    snapshot: snap,
    balance: balance,
    phase: phase,
    tip: tip
  };
}


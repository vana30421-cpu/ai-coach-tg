function checkContent3Integrity(){
  var issues = [];
  if(typeof LIFE_SPHERES === 'undefined' || LIFE_SPHERES.length < 7) issues.push('LIFE_SPHERES < 7');
  if(typeof SPHERE_RECOMMENDATIONS === 'undefined') issues.push('SPHERE_RECOMMENDATIONS');
  else {
    var total = 0;
    LIFE_SPHERES.forEach(function(s){
      if(!SPHERE_RECOMMENDATIONS[s.id] || SPHERE_RECOMMENDATIONS[s.id].length < 10) {
        issues.push('Рекомендаций для '+s.id+' < 10');
      }
      total += (SPHERE_RECOMMENDATIONS[s.id]||[]).length;
    });
    if(total < 100) issues.push('Всего рекомендаций < 100');
  }
  if(typeof HABITS_WITH_WHY === 'undefined' || HABITS_WITH_WHY.length < 100) issues.push('HABITS_WITH_WHY < 100');
  if(typeof HABIT_22_DAY_SYSTEM === 'undefined' || HABIT_22_DAY_SYSTEM.length < 22) issues.push('HABIT_22_DAY_SYSTEM < 22');
  if(typeof COACH_TIPS_2500 === 'undefined') issues.push('COACH_TIPS_2500');
  if(typeof ACHIEVEMENTS_333 === 'undefined' || ACHIEVEMENTS_333.length < 200) issues.push('ACHIEVEMENTS_333 < 200');
  if(typeof PROJECT_TEMPLATES === 'undefined' || PROJECT_TEMPLATES.length < 10) issues.push('PROJECT_TEMPLATES < 10');
  if(typeof NOTIFICATION_TYPES === 'undefined' || NOTIFICATION_TYPES.length < 20) issues.push('NOTIFICATION_TYPES < 20');
  if(typeof COACH_STYLES === 'undefined' || COACH_STYLES.length < 3) issues.push('COACH_STYLES < 3');
  return issues;
}


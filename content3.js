/* ============ ФУНКЦИЯ: РЕКОМЕНДАЦИЯ ДЛЯ СЛАБОЙ СФЕРЫ ============ */
function getRecommendationForWeakest(scores){
  var bal=getSpheresBalance(scores);
  if(!bal.weakest)return null;
  var recs=getSphereRecommendations(bal.weakest.id,bal.weakest.value||0);
  return recs.length?recs[0]:null;
}


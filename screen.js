/* ============ ФУНКЦИИ ============ */
function getScreenStats(){try{return JSON.parse(localStorage.getItem('screen_stats')||'{}')}catch(e){return{}}}
function saveScreenStats(data){try{localStorage.setItem('screen_stats',JSON.stringify(data))}catch(e){}}
function logScreenTime(minutes){
  var stats=getScreenStats();
  var today=new Date().toISOString().slice(0,10);
  if(!stats.daily)stats.daily={};
  if(!stats.daily[today])stats.daily[today]={minutes:0,entries:[]};
  stats.daily[today].minutes+=minutes;
  stats.daily[today].entries.push({time:new Date().toISOString(),minutes:minutes});
  saveScreenStats(stats);
}
function getTodayScreenTime(){
  var stats=getScreenStats();
  var today=new Date().toISOString().slice(0,10);
  return stats.daily&&stats.daily[today]?stats.daily[today].minutes:0;
}
function getWeekScreenTime(){
  var stats=getScreenStats();
  if(!stats.daily)return 0;
  var total=0;
  var today=new Date();
  for(var i=0;i<7;i++){
    var d=new Date(today);
    d.setDate(d.getDate()-i);
    var key=d.toISOString().slice(0,10);
    if(stats.daily[key])total+=stats.daily[key].minutes;
  }
  return total;
}
function toggleHabit(habitId){
  try{
    var habits=JSON.parse(localStorage.getItem('screen_habits')||'{}');
    var today=new Date().toISOString().slice(0,10);
    if(!habits[today])habits[today]=[];
    var idx=habits[today].indexOf(habitId);
    if(idx>=0)habits[today].splice(idx,1);else habits[today].push(habitId);
    localStorage.setItem('screen_habits',JSON.stringify(habits));
    return habits[today].indexOf(habitId)>=0;
  }catch(e){return false}
}
function isHabitDone(habitId){
  try{
    var habits=JSON.parse(localStorage.getItem('screen_habits')||'{}');
    var today=new Date().toISOString().slice(0,10);
    return habits[today]&&habits[today].indexOf(habitId)>=0;
  }catch(e){return false}
}
function getHabitStreak(habitId){
  try{
    var habits=JSON.parse(localStorage.getItem('screen_habits')||'{}');
    var streak=0;
    var today=new Date();
    for(var i=0;i<365;i++){
      var d=new Date(today);
      d.setDate(d.getDate()-i);
      var key=d.toISOString().slice(0,10);
      if(habits[key]&&habits[key].indexOf(habitId)>=0)streak++;
      else break;
    }
    return streak;
  }catch(e){return 0}
}
function startScreenMode(modeId){
  var mode=SCREEN_MODES[modeId];if(!mode)return null;
  var endTime=new Date(Date.now()+mode.duration*60*1000);
  try{
    localStorage.setItem('screen_mode',JSON.stringify({
      id:modeId,start:new Date().toISOString(),
      end:endTime.toISOString(),blocked:mode.blocked
    }));
  }catch(e){}
  return mode;
}
function getActiveMode(){
  try{
    var data=JSON.parse(localStorage.getItem('screen_mode')||'null');
    if(!data)return null;
    if(new Date(data.end)<new Date()){localStorage.removeItem('screen_mode');return null}
    return data;
  }catch(e){return null}
}


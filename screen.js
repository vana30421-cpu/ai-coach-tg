function getScreenHistory(){
  try{
    var s=window.state||state;
    return s.screenHistory||{};
  }catch(e){return{}}
}
function logScreenTime(date,minutes){
  try{
    var s=window.state||state;
    if(!s.screenHistory)s.screenHistory={};
    s.screenHistory[date]=parseFloat(minutes)||0;
    if(typeof window.save==='function')window.save();
    return true;
  }catch(e){return false}
}
function getAverageScreenDays(days){
  days=days||7;
  var h=getScreenHistory();
  var keys=Object.keys(h).sort().slice(-days);
  if(!keys.length)return 0;
  var sum=0;
  keys.forEach(function(k){sum+=h[k]||0});
  return Math.round(sum/keys.length);
}


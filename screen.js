/* ============ ПРОГРЕСС КУРСА ДЕТОКСА ============ */
function getDetoxProgress(){
  try{
    var s=window.state||state;
    if(!s.detoxCourseProgress)s.detoxCourseProgress={};
    return s.detoxCourseProgress;
  }catch(e){return{}}
}
function getCurrentDay(){
  var p=getDetoxProgress();
  var done=Object.keys(p).filter(function(k){return p[k]}).length;
  return Math.min(30,done+1);
}
function getCompletedDaysCount(){
  var p=getDetoxProgress();
  return Object.keys(p).filter(function(k){return p[k]}).length;
}
function isDayCompleted(day){
  var p=getDetoxProgress();
  return !!p[day];
}
function markDayCompleted(day){
  try{
    var s=window.state||state;
    if(!s.detoxCourseProgress)s.detoxCourseProgress={};
    s.detoxCourseProgress[day]=true;
    if(typeof window.save==='function')window.save();
    return true;
  }catch(e){return false}
}
function resetDetoxProgress(){
  try{
    var s=window.state||state;
    s.detoxCourseProgress={};
    if(typeof window.save==='function')window.save();
    return true;
  }catch(e){return false}
}


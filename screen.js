function startScreenMode(modeId){
  var mode=SCREEN_MODES[modeId];
  if(!mode)return null;
  var endTime=new Date(Date.now()+mode.duration*60*1000);
  try{
    localStorage.setItem('screen_mode',JSON.stringify({
      id:modeId,
      start:new Date().toISOString(),
      end:endTime.toISOString(),
      blocked:mode.blocked
    }));
  }catch(e){}
  return mode;
}

function getActiveMode(){
  try{
    var data=JSON.parse(localStorage.getItem('screen_mode')||'null');
    if(!data)return null;
    if(new Date(data.end)<new Date()){
      localStorage.removeItem('screen_mode');
      return null;
    }
    return data;
  }catch(e){return null}
}

